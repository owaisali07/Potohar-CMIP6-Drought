# v2.2 Item 6 (PREREGISTRATION.md): DEVIATIONS.md is generated from DEVIATIONS.template.md by placeholder substitution.
# A placeholder {{expr|fmt}} is an R expression evaluated with K = results_text/key_numbers.rds (data.table syntax allowed);
# fmt is the number of decimals (default 1), "i" (integer), "s" (text as is) or "+1"/"+2" (signed, typographic minus).
# Every substitution is logged to results_text/DEVIATIONS_trace.csv; an expression that does not give exactly one
# non-missing value stops the script. Historical values quoted from earlier versions are written literally in the template,
# in columns headed with that version, and are not regenerated.
suppressMessages(library(data.table))
cfg <- yaml::read_yaml(Sys.getenv("P6_CONFIG", "config.yaml")); ROOT <- cfg$paths$root
K <- readRDS(file.path(ROOT, "results_text", "key_numbers.rds"))
K <- lapply(K, function(x) if (is.data.frame(x)) as.data.table(x) else x)
tpl <- readLines(file.path(ROOT, "DEVIATIONS.template.md"), encoding = "UTF-8")
fmt1 <- function(v, f) {
  if (f == "s") return(as.character(v))
  v <- as.numeric(v)
  if (f == "i") return(format(round(v), big.mark = ",", scientific = FALSE, trim = TRUE))
  signed <- startsWith(f, "+"); d <- as.integer(sub("^\\+", "", f))
  s <- formatC(round(abs(v), d), format = "f", digits = d, big.mark = ",")
  if (signed) paste0(if (v >= 0) "+" else "−", s) else paste0(if (v < 0) "−" else "", s)
}
TRACE <- list(); pat <- "\\{\\{([^{}]+?)\\}\\}"
out <- vapply(seq_along(tpl), function(i) { x <- tpl[i]
  m <- gregexpr(pat, x, perl = TRUE)[[1]]; if (m[1] < 0) return(x)
  ph <- regmatches(x, list(m))[[1]]
  rep_ <- vapply(ph, function(p) { body <- sub("^\\{\\{", "", sub("\\}\\}$", "", p))
    parts <- strsplit(body, "|", fixed = TRUE)[[1]]; ex <- trimws(parts[1]); f <- if (length(parts) > 1) trimws(parts[2]) else "1"
    v <- eval(parse(text = ex), envir = list2env(list(K = K), parent = globalenv()))
    if (length(v) != 1 || is.na(v)) stop("DEVIATIONS template line ", i, ": '", ex, "' gave ", length(v), " value(s) or NA")
    s <- fmt1(v, f); TRACE[[length(TRACE) + 1]] <<- data.table(line = i, expression = ex, format = f, value = as.character(v), printed = s); s }, "")
  regmatches(x, list(m)) <- list(rep_); x }, "")
writeLines(enc2utf8(c("<!-- GENERATED by scripts/15_render_deviations.R from DEVIATIONS.template.md and results_text/key_numbers.rds; do not edit by hand. -->", out)),
           file.path(ROOT, "DEVIATIONS.md"), useBytes = TRUE)
fwrite(rbindlist(TRACE), file.path(ROOT, "results_text", "DEVIATIONS_trace.csv"))
cat("DEVIATIONS.md rendered:", length(TRACE), "placeholders substituted\n")
